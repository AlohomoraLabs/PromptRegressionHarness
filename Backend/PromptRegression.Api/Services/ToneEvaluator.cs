using System.Text.Json;
using PromptRegression.Api.Models;

namespace PromptRegression.Api.Services;

public class ToneEvaluator(
    ILlmService llmService)
{
    public async Task<ToneEvaluationResult> EvaluateAsync(
        string email,
        CancellationToken cancellationToken = default)
    {
        var prompt = $$"""
            You are evaluating an email generated by an AI system.

            Evaluate the email for:

            1. Tone
            - Is it professional?
            - Is it friendly?
            - Does it sound natural?
            - Does it avoid aggressive sales language?

            2. Spamminess
            - Does it sound like spam?
            - Does it use excessive urgency?
            - Does it make exaggerated claims?
            - Does it pressure the recipient?

            EMAIL:

            {{email}}

            Scoring:

            ToneScore:
            1 = very unprofessional or unnatural
            10 = professional, natural and friendly

            SpamScore:
            1 = not spammy
            10 = extremely spammy

            The email passes when:
            - ToneScore is 6 or higher
            - SpamScore is 4 or lower

            Return JSON only using this exact structure:

            {
              "passed": true,
              "toneScore": 8,
              "spamScore": 2,
              "reason": "The email is friendly and professional without sounding overly promotional."
            }

            Do not include markdown.
            Do not include ```json.
            Do not include explanations outside the JSON object.
            """;

        var response = await llmService.GenerateJsonAsync(
            prompt,
            cancellationToken);

        return ParseResult(response);
    }

    private static ToneEvaluationResult ParseResult(
        string response)
    {
        try
        {
            return JsonSerializer.Deserialize<ToneEvaluationResult>(
                response,
                new JsonSerializerOptions
                {
                    PropertyNameCaseInsensitive = true
                })
                ?? new ToneEvaluationResult
                {
                    Passed = false,
                    Reason = "Could not parse evaluator response."
                };
        }
        catch
        {
            return new ToneEvaluationResult
            {
                Passed = false,
                Reason = "Could not parse evaluator response as JSON."
            };
        }
    }
}